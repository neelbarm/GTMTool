/* --- Documents for the non-flagship persona returns ----------------------- */

function doc(
  id: string,
  returnId: string,
  kind: SourceDoc["kind"],
  issuer: string,
  uploadedBy: string,
  daysAgo: number,
  values: number[],
  status: SourceDoc["status"] = "processed",
): SourceDoc {
  return {
    id,
    returnId,
    name: `${kind} — ${issuer}.pdf`,
    kind,
    issuer,
    pages: 1,
    bytes: 120_000,
    uploadedBy,
    uploadedAt: day(-daysAgo),
    source: uploadedBy === "system" ? "bank-connect" : "client-upload",
    status,
    confidence: 0.94,
    taxYear: 2025,
    facsimile: genericFacsimile(kind, issuer, 2025, values),
  };
}

